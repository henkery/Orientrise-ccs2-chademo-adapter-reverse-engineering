#!/usr/bin/env python3
"""analyze86.py — power-stage GPIO active-level + safe-state decoder (§5.5c/§5.17, custom_fw).
Complements analyze78/81 (which NAMED the pins): this decodes each C013 drive primitive's BSRR
set/reset logic to determine the pin's ACTIVE level, then derives the SAFE (de-asserted) level
the custom firmware must drive at boot so every contactor stays OPEN and no HV can appear.

BSRR semantics: low 16 bits = SET mask (write 1 -> pin HIGH), high 16 bits = RESET mask
(write 1 -> pin LOW). A primitive writes `set_mask | (reset_mask << 16)`:
  - active-HIGH: `and r0,r0,#1` then `orr rX, rY, r0, lsl #n` -> cmd=1 SETS pin n (HIGH).
    SAFE = LOW (reset). Used by CHAdeMO d1/d2 (PE7/PE8), BatteryPower (PD8), PreCharge (PB10/11).
  - active-LOW: `bics rX, rY` (inverted cmd) then `orr ... rX, lsl #n` -> cmd=1 RESETS pin n
    (LOW). SAFE = HIGH (set). Used by BatteryCharge (PC9), e-lock motor (PD3/PE4).

The PreChargeRELAY reset masks are generated by an address-bit trick (`lsls r2, r1, #0x10/0x11`
where r1=GPIOB base 0x40020400 whose bit10 survives the shift -> (1<<10/11)<<16), so the SET
shift (`r0, lsl #10/11`) is the reliable pin indicator.

Usage:
  nix-shell -p python3 python3Packages.capstone --run 'python3 analyze86.py'
"""
import struct
from capstone import Cs, CS_ARCH_ARM, CS_MODE_THUMB, CS_MODE_LITTLE_ENDIAN
from capstone.arm_const import ARM_REG_LR

TB = 0x0801FBFE
fw = open('.qwen/tmp/c013/decoded_c013.bin', 'rb').read(); N = len(fw)
md = Cs(CS_ARCH_ARM, CS_MODE_THUMB | CS_MODE_LITTLE_ENDIAN); md.detail = True
def u16(o): return struct.unpack_from('<H', fw, o)[0]
def u32(o): return struct.unpack_from('<I', fw, o)[0]
def rt(f): return TB + f
def ldr_pool(o):
    h1 = u16(o)
    if (h1 & 0xF800) == 0x4800:
        p = (((rt(o)+4) & ~3) - TB) + (h1 & 0xFF)*4
        if 0 <= p and p+4 <= N: return u32(p)
    return None
GPIO = {0x40020000:'A', 0x40020400:'B', 0x40020800:'C', 0x40020C00:'D', 0x40021000:'E'}

# C013 drive primitives (analyze81): (signal, address, expected pins)
PRIMS = [
    ('CHAdeMO enable d1', 0x08088400),
    ('CHAdeMO enable d2', 0x08088412),
    ('BatteryPower (inner contactor)', 0x08088450),
    ('e-lock motor', 0x0808846C),
    ('PreChargeRELAY', 0x08088498),
    ('BatteryCharge', 0x080884D4),
]

def decode(addr):
    """Return (pins [(port,n)], active_low) by reading the primitive's BSRR logic."""
    a = addr - TB
    regbase = {}; alow = False; pins = []; last_inv = None
    for _ in range(40):
        ins = list(md.disasm(fw[a:a+8], rt(a), count=1))
        if not ins: a += 2; continue
        i = ins[0]; ops = i.operands; mn = i.mnemonic
        w = ldr_pool(a)
        if mn in ('ldr','ldr.w') and w in GPIO and len(ops)==2:
            regbase[ops[0].reg] = w
        elif mn == 'bics':
            alow = True
        elif mn in ('orr','orr.w') and len(ops)==3 and ops[2].type==1 and ops[2].shift.value>0:
            sh = ops[2].shift.value
            if sh <= 15:
                # the shifted source register carries the cmd (active-high) or inverted cmd (active-low)
                src = ops[2].reg
                bb = regbase.get(ops[1].mem.base) if ops[1].type==3 else None
                # find which GPIO this BSRR write targets via the base of the paired str (tracked below)
                pins.append((src, sh))
        elif mn in ('str','str.w') and len(ops)==2 and ops[1].type==3 and ops[1].mem.disp==0x18:
            bb = regbase.get(ops[1].mem.base)
            if bb is not None and pins:
                src, sh = pins[-1]
                pins[-1] = (GPIO[bb], sh)
        a += i.size
        if mn=='bx' and ops and ops[0].type==1 and ops[0].reg==ARM_REG_LR: break
        if mn=='pop' and any(op.type==1 and op.reg==81 for op in ops): break
    # keep only resolved (port,n) pins
    out = [(p, n) for p, n in pins if isinstance(p, str)]
    # de-dup preserving order
    seen = []; 
    for x in out:
        if x not in seen: seen.append(x)
    return seen, alow

print("== C013 power-stage GPIO active levels + SAFE (de-asserted) boot state ==")
print(f"  {'signal':32s} {'pin(s)':12s} {'active':8s} {'SAFE level':10s} primitive")
safe_rows = []
for name, addr in PRIMS:
    pins, alow = decode(addr)
    ps = '+'.join(f'P{p}{n}' for p, n in pins)
    active = 'LOW' if alow else 'HIGH'
    safe = 'HIGH' if alow else 'LOW'
    print(f"  {name:32s} {ps:12s} {active:8s} {safe:10s} 0x{addr:08X}")
    for p, n in pins:
        safe_rows.append((p, n, safe, name))

print("\n== Safe-state boot table (custom_fw gpio_safe_init) ==")
print("  Drive these DE-ASSERTED levels (BSRR pre-load while pins are inputs, then MODER->output):")
for p, n, safe, name in safe_rows:
    bsrr = f'SET({n})' if safe=='HIGH' else f'RESET({n})'
    print(f"    P{p}{n:<2d} -> {safe:4s}  ({bsrr:10s})  ; {name}")
print("\n  active-HIGH contactor/enable pins SAFE=LOW (open/disabled); active-LOW charge/e-lock")
print("  pins SAFE=HIGH (off). No asserted level is ever driven during init => contactors open, no HV.")
